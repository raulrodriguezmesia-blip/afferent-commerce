"""
Email Dispatcher Service for Afferent Commerce.

Asynchronous email dispatch with PDF attachment support.
Uses SMTP (Gmail) or a simulated dispatcher for demo mode.
"""
import os
import smtplib
import asyncio
from email.message import EmailMessage
from typing import Optional
from concurrent.futures import ThreadPoolExecutor

SMTP_HOST = os.getenv("SMTP_HOST", "smtp.gmail.com")
SMTP_PORT = int(os.getenv("SMTP_PORT", "587"))
SMTP_USER = os.getenv("SMTP_USER", "")
SMTP_PASSWORD = os.getenv("SMTP_PASSWORD", "")
SMTP_FROM = os.getenv("SMTP_FROM", "noreply@afferent-commerce.internal")

_executor = ThreadPoolExecutor(max_workers=2)


def _send_email_sync(recipient: str, subject: str, body: str, pdf_bytes: Optional[bytes] = None, pdf_filename: str = "report.pdf"):
    """Synchronous email send (runs in thread pool)."""
    msg = EmailMessage()
    msg['Subject'] = subject
    msg['From'] = SMTP_FROM
    msg['To'] = recipient
    msg.set_content(body)

    if pdf_bytes:
        msg.add_attachment(pdf_bytes, maintype='application', subtype='pdf', filename=pdf_filename)

    if SMTP_USER and SMTP_PASSWORD:
        with smtplib.SMTP(SMTP_HOST, SMTP_PORT) as server:
            server.starttls()
            server.login(SMTP_USER, SMTP_PASSWORD)
            server.send_message(msg)
        return {"status": "sent", "recipient": recipient, "method": "smtp"}
    else:
        # Simulated dispatch for demo mode
        return {"status": "simulated", "recipient": recipient, "method": "demo", "message": "Email simulated (no SMTP credentials configured)"}


async def send_audit_report_email(recipient_email: str, pdf_bytes: bytes, order_id: str, subject: Optional[str] = None):
    """Async email dispatch with PDF attachment."""
    if not subject:
        subject = f"ISO Audit Report & PayPal Settlement - Order {order_id}"
    body = (
        f"Attached is the executive ISO compliance audit report and settlement summary "
        f"for PayPal Order {order_id}.\n\n"
        f"This report includes:\n"
        f"  - Conformity status (ISO 10218-1, ISO/TS 15066, IEC 61508)\n"
        f"  - Tribological material profile\n"
        f"  - Force budget and safety margins\n"
        f"  - Neuromorphic reflex telemetry\n"
        f"  - Acoustic-slip spectrogram analysis\n"
        f"  - Multi-digit topology\n"
        f"  - NVIDIA Nemotron AI diagnosis\n\n"
        f"Generated by Afferent Commerce - Agentic Quality Control Platform\n"
    )
    loop = asyncio.get_event_loop()
    result = await loop.run_in_executor(
        _executor, _send_email_sync, recipient_email, subject, body, pdf_bytes, f"Audit_Report_{order_id}.pdf"
    )
    return result


async def send_notification_email(recipient_email: str, subject: str, body: str):
    """Async simple notification email."""
    loop = asyncio.get_event_loop()
    result = await loop.run_in_executor(
        _executor, _send_email_sync, recipient_email, subject, body, None, ""
    )
    return result
